/* Kept in recovery so a broken main image cannot take away the upload page. */
static const char recovery_page[] =
    "<!doctype html>\n"
    "<html lang=\"en\">\n"
    "<meta charset=\"utf-8\">\n"
    "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1\">\n"
    "<title>perINKpheral recovery</title>\n"
    "<style>\n"
    "body{margin:48px auto;padding:0 24px;max-width:560px;background:#e9e7e1;color:#141413;font:16px monospace}\n"
    "h1{font-size:24px;font-weight:normal}p{line-height:1.6}button,input{font:inherit;margin:12px 0}\n"
    "button{padding:12px 18px;border:1px solid;background:none;color:inherit;cursor:pointer}\n"
    "button:disabled{opacity:.5;cursor:wait}input{max-width:100%}#result{white-space:pre-wrap}\n"
    "</style>\n"
    "<h1>perINKpheral recovery</h1>\n"
    "<p>Your settings and applications are kept. Choose a firmware file, then confirm its installation with OK on the device.</p>\n"
    "<p>To try the installed firmware, press BACK on the device.</p>\n"
    "<form id=\"upload\">\n"
    "<label for=\"image\">Firmware file</label><br>\n"
    "<input type=\"file\" id=\"image\" accept=\".bin\" required><br>\n"
    "<button id=\"send\">Install firmware</button>\n"
    "</form>\n"
    "<p id=\"result\" role=\"status\" aria-live=\"polite\"></p>\n"
    "<script>\n"
    "\"use strict\";\n"
    "const form = document.getElementById(\"upload\");\n"
    "const input = document.getElementById(\"image\");\n"
    "const button = document.getElementById(\"send\");\n"
    "const output = document.getElementById(\"result\");\n"
    "const pause = () => new Promise(resolve => setTimeout(resolve, 2000));\n"
    "async function readStatus() {\n"
    "  try {\n"
    "    const response = await fetch(\"/api/status\", {cache:\"no-store\", signal:AbortSignal.timeout(4000)});\n"
    "    return response.ok ? await response.json() : null;\n"
    "  } catch (error) { return null; }\n"
    "}\n"
    "async function uploadOnce(file) {\n"
    "  let response;\n"
    "  try {\n"
    "    response = await fetch(\"/api/ota\", {method:\"POST\", body:file, signal:AbortSignal.timeout(300000)});\n"
    "  } catch (error) { return; }\n"
    "  if (!response.ok) {\n"
    "    let message = \"HTTP \" + response.status;\n"
    "    try {\n"
    "      const text = await response.text();\n"
    "      try { message = JSON.parse(text).error || text; } catch (error) { message = text; }\n"
    "    } catch (error) { /* The status remains useful if its body was interrupted. */ }\n"
    "    throw Error(message);\n"
    "  }\n"
    "}\n"
    "form.onsubmit = async event => {\n"
    "  event.preventDefault();\n"
    "  const file = input.files[0];\n"
    "  if (!file || button.disabled) return;\n"
    "  button.disabled = input.disabled = true;\n"
    "  try {\n"
    "    output.textContent = \"Checking firmware.\";\n"
    "    if (file.size < 304 || file.size > 2 * 1024 * 1024) throw Error(\"Invalid image size.\");\n"
    "    const head = new Uint8Array(await file.slice(0, 304).arrayBuffer());\n"
    "    const view = new DataView(head.buffer);\n"
    "    const field = offset => new TextDecoder().decode(head.slice(offset, offset + 32)).split(\"\\0\")[0];\n"
    "    if (head[0] !== 0xe9 || view.getUint32(32, true) !== 0xabcd5432 ||\n"
    "        field(80) !== \"perinkpheral\" || view.getUint32(288, true) !== 0x54524150 ||\n"
    "        !head.slice(48, 80).includes(0) || !field(48)) throw Error(\"Invalid firmware image.\");\n"
    "    const expectedVersion = field(48);\n"
    "    const expectedImage = Array.from(head.slice(176, 208), byte => byte.toString(16).padStart(2, \"0\")).join(\"\");\n"
    "    const recovery = await readStatus();\n"
    "    if (!recovery) throw Error(\"Device not found. Check its screen and network address.\");\n"
    "    if (recovery.mode !== \"recovery\") throw Error(\"Recovery is no longer active. Reload this page.\");\n"
    "    if (recovery.ota_protocol !== 1 || !Number.isInteger(recovery.boot_id)) {\n"
    "      throw Error(\"Unsupported firmware update protocol.\");\n"
    "    }\n"
    "    if (recovery.partition_table !== view.getUint32(292, true)) {\n"
    "      throw Error(\"Image is for another partition table. Flash over USB.\");\n"
    "    }\n"
    "    output.textContent = \"Confirm with OK on the device. Keep this page open.\";\n"
    "    await uploadOnce(file);\n"
    "    output.textContent = \"Waiting for the new firmware to finish its checks.\";\n"
    "    const deadline = Date.now() + 300000;\n"
    "    while (Date.now() < deadline) {\n"
    "      await pause();\n"
    "      const current = await readStatus();\n"
    "      if (!current) continue;\n"
    "      if (current.mode === \"recovery\") {\n"
    "        if (current.boot_id !== recovery.boot_id) throw Error(\"Firmware did not start. Choose a file to try again.\");\n"
    "        if ([\"idle\", \"failed\"].includes(current.upload_state)) {\n"
    "          throw Error(\"Upload stopped. Choose a file and confirm again.\");\n"
    "        }\n"
    "      }\n"
    "      if (current.mode === \"application\" && current.on_probation === false) {\n"
    "        if (current.firmware !== expectedVersion || current.image_id !== expectedImage) {\n"
    "          throw Error(\"A different firmware started. The uploaded image was not confirmed.\");\n"
    "        }\n"
    "        location.reload();\n"
    "        return;\n"
    "      }\n"
    "    }\n"
    "    throw Error(\"Device not found. Check its screen and reconnect to its Wi-Fi if needed.\");\n"
    "  } catch (error) {\n"
    "    output.textContent = error.message;\n"
    "  } finally {\n"
    "    button.disabled = input.disabled = false;\n"
    "  }\n"
    "};\n"
    "</script>\n"
    "</html>\n";
