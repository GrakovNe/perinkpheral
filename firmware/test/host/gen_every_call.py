"""Writes an application that imports every call of sdk/host_api.h.

It calls none of them: it takes the address of each, which is enough for
the module to import it with the signature the header gives. Loading it is
then the check that the host's table has every call, each with the
signature the header says - for the calls no other test happens to make.
"""
import json
import os
import re
import sys

header, out_dir = sys.argv[1], sys.argv[2]
with open(header) as f:
    calls = re.findall(r"^HOST_(?:SYSTEM_)?IMPORT\(\w+,\s*[^;]*?\b(\w+)\(", f.read(), re.M | re.S)
if len(calls) < 60:
    sys.exit("%s: only %d calls found - the header is read wrong" % (header, len(calls)))

os.makedirs(out_dir, exist_ok=True)
with open(os.path.join(out_dir, "every_call.c"), "w") as f:
    f.write("/* Generated by gen_every_call.py from host_api.h. */\n")
    f.write('#include "host_api.h"\n\n')
    f.write("typedef void (*call_t)(void);\n")
    f.write("static const call_t CALLS[] = {\n")
    for call in calls:
        f.write("    (call_t)%s,\n" % call)
    f.write("};\n\nstatic volatile call_t taken;\n\n")
    f.write("void app_on_timer(int32_t id)\n{\n")
    f.write("    taken = CALLS[(uint32_t)id %% %d];\n}\n" % len(calls))
with open(os.path.join(out_dir, "manifest.json"), "w") as f:
    json.dump({"name": os.path.basename(os.path.normpath(out_dir)), "title": "Every call", "abi": 2, "system": True}, f)
with open(os.path.join(out_dir, "count.h"), "w") as f:
    f.write("#define EVERY_CALL_COUNT %d\n" % len(calls))
