package org.perinkpheral.core.contract

import org.perinkpheral.core.BuildError
import org.perinkpheral.core.build.Sdk
import java.security.MessageDigest
import java.io.File
import java.nio.file.Files

/** A recorded entry can never be removed or changed. New entries are compatible additions. */
object ContractSnapshot {
    private val ignored = setOf("HOST_IMPORT", "HOST_SYSTEM_IMPORT", "HOST_LAYOUT")

    fun run(sdk: Sdk, wasi: File, out: File, check: Boolean) {
        val current = entries(sdk, wasi)
        if (out.isFile) {
            val recorded = read(out)
            val broken = recorded.filter { (key, value) -> current[key] != value }
            if (broken.isNotEmpty()) throw BuildError("Frozen ABI changed:\n" + broken.entries.joinToString("\n") {
                "  ${it.key}: recorded ${it.value}; now ${current[it.key] ?: "missing"}"
            })
        } else if (check) throw BuildError("Missing frozen contract: ${out.path}")
        if (!check) {
            out.parentFile?.mkdirs()
            out.writeText("# SPDX-License-Identifier: MIT\n# ABI ${sdk.hostApiVersion}; generated by tools/perinkpheral contract snapshot.\n" +
                current.toSortedMap().entries.joinToString("") { "${it.key}\t${it.value}\n" })
        }
        println("${current.size} ABI ${sdk.hostApiVersion} entries ${if (check) "checked" else "recorded"}: ${out.path}")
    }

    private fun read(file: File): Map<String, String> {
        val entries = linkedMapOf<String, String>()
        file.readLines().filter { it.isNotBlank() && !it.startsWith('#') }.forEach { line ->
            val parts = line.split('\t', limit = 2)
            if (parts.size != 2 || entries.put(parts[0], parts[1]) != null) throw BuildError("Invalid snapshot entry: $line")
        }
        if (entries.isEmpty()) throw BuildError("Empty contract snapshot: ${file.path}")
        return entries
    }

    private fun entries(sdk: Sdk, wasi: File): Map<String, String> {
        val contract = sdk.contract
        val entries = linkedMapOf<String, String>()
        contract.calls.forEach {
            val grant = when { it.isSystem -> "system"; it.name == "file_write" -> "writes_files"; else -> "none" }
            entries["import ${it.name}"] = "${it.signature.replace('*', 'i')} grant=$grant"
            entries["since ${it.name}"] = sdk.callSince[it.name] ?: sdk.firmwareFirst
        }
        contract.exports.forEach { entries["export ${it.name}"] = it.signature.replace('*', 'i') }
        sdk.limits.forEach { (name, value) -> entries["constant MANIFEST_$name"] = value.toString() }
        val text = contract.text
            .replace(Regex("""/\*.*?\*/""", RegexOption.DOT_MATCHES_ALL), " ")
            .replace("\\\n", " ")
        val measures = linkedMapOf<String, String>()
        Regex("""^#define[ \t]+((?:HOST_|BTN_|SYS_)\w+)(\([^\n]*?\))?[ \t]+([^\n]+)""", RegexOption.MULTILINE)
            .findAll(text).forEach {
                val (name, parameters, body) = it.destructured
                if (name in ignored) return@forEach
                if (parameters.isNotEmpty()) entries["macro $name"] = (parameters + " " + body).trim().replace(Regex("\\s+"), " ")
                else if (body.trim().startsWith('"')) entries["constant $name"] = body.trim()
                else measures["constant $name"] = "(long long)($name)"
            }
        Regex("""typedef\s+struct(?:\s+\w+)?\s*\{([^{}]*)}\s*(\w+)\s*;""").findAll(text).forEach { record ->
            val (body, type) = record.destructured
            measures["struct $type size"] = "sizeof($type)"
            measures["struct $type align"] = "_Alignof($type)"
            body.split(';').filter { it.isNotBlank() }.forEach { declaration ->
                val members = declaration.trim().split(',')
                val first = Regex("""^(.+?)([A-Za-z_]\w*)(\s*\[[^]]+])?$""").matchEntire(members.first().trim())
                    ?: throw BuildError("Cannot read $type: $declaration")
                val fieldType = first.groupValues[1].trim().replace(Regex("\\s+"), " ")
                members.forEachIndexed { index, member ->
                    val declared = if (index == 0) first.groupValues[2] + first.groupValues[3] else member.trim()
                    val field = declared.substringBefore('[').trim()
                    val array = declared.substringAfter('[', "").removeSuffix("]")
                    entries["field $type.$field type"] = fieldType + if (array.isEmpty()) "" else "[$array]"
                    measures["field $type.$field offset"] = "__builtin_offsetof($type, $field)"
                    measures["field $type.$field size"] = "sizeof((($type *)0)->$field)"
                }
            }
        }
        val scratch = Files.createTempDirectory("perinkpheral-contract-").toFile()
        try {
            val source = File(scratch, "contract.c")
            source.writeText("/* SPDX-License-Identifier: MIT */\n#include \"host_api.h\"\n" +
                measures.values.mapIndexed { index, expression -> "const long long measure_$index = $expression;\n" }.joinToString(""))
            val output = File(scratch, "contract.ll")
            val process = ProcessBuilder(File(wasi, "bin/clang").path, "--target=wasm32", "-std=c11", "-S", "-emit-llvm",
                "-I${sdk.sdk.path}", source.path, "-o", output.path).redirectErrorStream(true).start()
            val errors = process.inputStream.bufferedReader().readText()
            if (process.waitFor() != 0) throw BuildError("Contract layout compilation failed:\n$errors")
            val values = Regex("""@measure_(\d+) = [^\n]*?constant i64 (-?\d+)""").findAll(output.readText())
                .associate { it.groupValues[1].toInt() to it.groupValues[2] }
            measures.keys.forEachIndexed { index, key -> entries[key] = values[index] ?: throw BuildError("Compiler omitted $key") }
        } finally { scratch.deleteRecursively() }
        val packages = File(sdk.sdk, "abi/${sdk.hostApiVersion}")
        if (packages.isDirectory) {
            packages.walkTopDown().filter { it.isFile && it.extension != "md" }.forEach { file ->
                val digest = MessageDigest.getInstance("SHA-256").digest(file.readBytes())
                entries["fixture ${file.relativeTo(packages).invariantSeparatorsPath}"] =
                    digest.joinToString("") { "%02x".format(it) }
            }
        }
        return entries
    }
}
