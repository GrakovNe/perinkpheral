        0x2116 to "No",
        0x20AC to "EUR",
        0xD7 to "x",
        0xB7 to ".",
        0x2022 to "*",
        0x2212 to "-",
    )

    private val RANGES = listOf(Triple("LATIN", 0x00A0, 0x017F), Triple("GREEK", 0x0386, 0x03CE),
        Triple("CYRILLIC", 0x0400, 0x04FF), Triple("SIGNS", 0x2010, 0x2030))

    private fun capital(spelled: String) = spelled.take(1).uppercase(Locale.ROOT) + spelled.drop(1)

    /** How the character is written in ASCII, or null. */
    fun spelling(cp: Int): String? {
        SIGNS[cp]?.let { return it }
        val char = String(Character.toChars(cp))
        val small = char.lowercase(Locale.ROOT)
        for (table in listOf(CYRILLIC, GREEK, LATIN)) {
            table[small]?.let { return if (char == small) it else capital(it) }
        }
        // A letter with a mark is its letter: what is left of it taken apart.
        val base = Normalizer.normalize(char, Normalizer.Form.NFD)
            .filter { Character.getType(it) != Character.NON_SPACING_MARK.toInt() }
        if (base != char && base.isNotEmpty() && base.all { it.code in 0x21 until 0x7F }) return base
        if (base.length == 1 && base != char) return spelling(base[0].code)
        return null
    }

    /** Writes the header; says how many characters are spelled. */
    fun make(out: File): String {
        val lines = mutableListOf("/* generated by tools/perinkpheral spelling - do not edit */", "#pragma once", "",
            "#include <stdint.h>", "",
            "/* How a character the device has no glyph for is spelled in ASCII: a table a",
            " * range of code points, NULL for what has no spelling. */", "")
        for ((name, first, last) in RANGES) {
            lines += "static const char *const SPELLING_$name[] = {"
            for (cp in first..last) {
                val spelled = if (cp !in setOf(0x20AC, 0x2116) || name == "SIGNS") spelling(cp) else null
                val text = if (spelled == null) "NULL" else "\"" + spelled.replace("\\", "\\\\").replace("\"", "\\\"") + "\""
                lines += String.format(Locale.ROOT, "    /* U+%04X */ %s,", cp, text)
            }
            lines += "};"
            lines += ""
        }
        lines += listOf("static const struct {", "    uint16_t           first, last;", "    const char *const *spelled;", "} SPELLINGS[] = {")
        for ((name, first, last) in RANGES) lines += String.format(Locale.ROOT, "    { 0x%04X, 0x%04X, SPELLING_%s },", first, last, name)
        lines += "};"
        lines += ""
        val extra = SIGNS.keys.filter { cp -> RANGES.none { (_, first, last) -> cp in first..last } }.sorted()
        lines += listOf("static const struct {", "    uint16_t    cp;", "    const char *spelled;", "} SPELLING_SINGLES[] = {")
        for (cp in extra) lines += String.format(Locale.ROOT, "    { 0x%04X, \"%s\" },", cp, SIGNS.getValue(cp))
        lines += "};"
        out.writeText(lines.joinToString("\n") + "\n")
        val count = RANGES.sumOf { (_, first, last) -> (first..last).count { spelling(it) != null } }
        return "${out.path}: ${count + extra.size} characters spelled"
    }
