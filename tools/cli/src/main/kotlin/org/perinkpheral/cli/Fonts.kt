package org.perinkpheral.cli

import org.perinkpheral.core.BuildError
import java.io.File

/**
 * A font into a C header for gfx_text_font(): one bit a pixel, as the panel shows it. The
 * characters are printable ASCII and what `extra` adds - or `only` those and '?'; code points
 * the font lacks are left out and draw as '?' on the device.
 */
object Fonts {
    private val ASCII = (0x20 until 0x7F).toList()

    /** Rows a bit a pixel, the leftmost the highest, each row in whole bytes. */
    fun packRows(rows: List<BooleanArray>, width: Int): ByteArray {
        val out = java.io.ByteArrayOutputStream()
        for (row in rows) {
            var byte = 0
            var count = 0
            for (x in 0 until width) {
                byte = (byte shl 1) or (if (row[x]) 1 else 0)
                if (++count == 8) {
                    out.write(byte); byte = 0; count = 0
                }
            }
            if (count > 0) out.write(byte shl (8 - count))
        }
        return out.toByteArray()
    }

    /** "18.6667", "11": a size as the headers say it. */
    fun sizeText(px: Double): String =
        if (px == Math.floor(px)) px.toLong().toString()
        else String.format(java.util.Locale.ROOT, "%.6g", px).trimEnd('0').trimEnd('.')

    fun header(font: File, source: String, px: Double, name: String, out: File, extra: String = "", only: String? = null): String {
        val face = FontFace(font, px)
        val wanted = (if (only != null) only.codePoints().toArray().toList() + '?'.code else ASCII + extra.codePoints().toArray().toList()).distinct()
        val glyphs = ArrayList<IntArray>()
        val bits = java.io.ByteArrayOutputStream()
        val missing = StringBuilder()
        for (cp in wanted) {
            val glyph = face.glyph(cp)
            if (glyph == null) {
                missing.appendCodePoint(cp)
                continue
            }
            glyphs += intArrayOf(cp, glyph.width, glyph.height, glyph.left, glyph.top, glyph.advance, bits.size())
            bits.write(packRows(glyph.rows, glyph.width))
        }
        if (glyphs.none { it[0] == '?'.code }) throw BuildError("${font.name} has no '?', which is the fallback glyph")
        glyphs.sortWith(compareBy({ it[0] }, { it[1] }, { it[2] }, { it[3] }, { it[4] }, { it[5] }, { it[6] }))
        val data = bits.toByteArray()
        out.parentFile?.mkdirs()
        out.writeText(buildString {
            append("/* generated by tools/perinkpheral font from $source at ${sizeText(px)} px - do not edit */\n")
            append("#pragma once\n\n#include \"gfx.h\"\n\n")
            append("static const uint8_t ${name}_bits[${data.size}] = {\n")
            for (start in data.indices step 16) {
                append("    " + data.copyOfRange(start, minOf(start + 16, data.size)).joinToString(",") { String.format(java.util.Locale.ROOT, "0x%02X", it.toInt() and 0xFF) } + ",\n")
            }
            append("};\n\n")
            append("static const gfx_glyph_t ${name}_glyphs[${glyphs.size}] = {\n")
            append("    /* cp, w, h, left, top, advance, offset */\n")
            glyphs.forEach { (cp, w, h, left, top, advance, offset) ->
                append(String.format(java.util.Locale.ROOT, "    { 0x%04X, %d, %d, %d, %d, %d, %d },\n", cp, w, h, left, top, advance, offset))
            }
            append("};\n\n")
            append("enum { ${name}_ascent = ${face.ascent}, ${name}_descent = ${face.descent}, ${name}_count = ${glyphs.size} };\n\n")
            append("static const gfx_font_t $name = {\n")
            append("    .ascent = ${name}_ascent, .descent = ${name}_descent, .glyphs = ${name}_glyphs,\n")
            append("    .count = ${name}_count, .bits = ${name}_bits, .scale = 1,\n")
            append("};\n")
        })
        return "$name: ${sizeText(px)} px, ascent ${face.ascent}, descent ${face.descent}, ${glyphs.size} glyphs, ${data.size} bytes of bitmaps" +
            if (missing.isNotEmpty()) ", missing: $missing" else ""
    }

    private operator fun IntArray.component6() = this[5]
    private operator fun IntArray.component7() = this[6]
}
