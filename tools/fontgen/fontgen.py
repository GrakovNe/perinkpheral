"""TTF/OTF -> 1-bit bitmap font as a C header for gfx_text_font().

    tools/fontgen/fontgen.py assets/fonts/DepartureMono-Regular.otf \
        --px 22 --name departure_22 --out firmware/components/gfx/fonts/departure_22.h \
        --preview departure_22.png --sample "ver 1.234.5 (c) 2026 Max Grakov"

Rasterizes with FreeType in monochrome mode (no antialiasing: the panel
is 1-bit). Character set: printable ASCII and whatever `--chars`
adds; code points the font lacks are left out and
draw as '?' on the device. Needs the freetype-py package
(`pip install freetype-py`, in a virtualenv of your choice).
"""
import argparse
import os
import struct
import sys
import zlib

try:
    import freetype
except ImportError:
    sys.exit("freetype-py is missing: pip install freetype-py")

ASCII = [chr(c) for c in range(0x20, 0x7F)]


def render(face, cp):
    """Returns (w, h, left, top, advance, rows) with rows as lists of bools, or None."""
    idx = face.get_char_index(cp)
    if idx == 0:
        return None
    face.load_glyph(idx, freetype.FT_LOAD_RENDER | freetype.FT_LOAD_TARGET_MONO
                    | freetype.FT_LOAD_MONOCHROME)
    g = face.glyph
    bm = g.bitmap
    rows = []
    for y in range(bm.rows):
        row = []
        for x in range(bm.width):
            byte = bm.buffer[y * bm.pitch + (x >> 3)]
            row.append((byte >> (7 - (x & 7))) & 1 == 1)
        rows.append(row)
    return bm.width, bm.rows, g.bitmap_left, g.bitmap_top, (g.advance.x + 32) >> 6, rows


def pack_rows(rows, w):
    """1 = ink, MSB left, rows padded to a byte (the font's own format)."""
    out = bytearray()
    for row in rows:
        byte = 0
        n = 0
        for x in range(w):
            byte = (byte << 1) | (1 if row[x] else 0)
            n += 1
            if n == 8:
                out.append(byte)
                byte, n = 0, 0
        if n:
            out.append(byte << (8 - n))
    return bytes(out)


def write_header(path, name, px, ascent, descent, glyphs, bits, source):
    with open(path, "w") as f:
        f.write("/* generated by tools/fontgen/fontgen.py from %s at %d px - do not edit */\n"
                % (source, px))
        f.write("#pragma once\n\n#include \"gfx.h\"\n\n")
        f.write("static const uint8_t %s_bits[%d] = {\n" % (name, len(bits)))
        for i in range(0, len(bits), 16):
            f.write("    " + ",".join("0x%02X" % b for b in bits[i:i + 16]) + ",\n")
        f.write("};\n\n")
        f.write("static const gfx_glyph_t %s_glyphs[%d] = {\n" % (name, len(glyphs)))
        f.write("    /* cp, w, h, left, top, advance, offset */\n")
        for cp, w, h, left, top, adv, off in glyphs:
            f.write("    { 0x%04X, %d, %d, %d, %d, %d, %d },\n" % (cp, w, h, left, top, adv, off))
        f.write("};\n\n")
        f.write("static const gfx_font_t %s = {\n" % name)
        f.write("    .ascent = %d, .descent = %d, .glyphs = %s_glyphs, .count = %d, .bits = %s_bits,\n"
                % (ascent, descent, name, len(glyphs), name))
        f.write("};\n")


def write_png(path, canvas, scale):
    w = len(canvas[0]) * scale
    h = len(canvas) * scale
    raw = bytearray()
    for row in canvas:
        line = bytearray()
        for black in row:
            line += (b"\x14\x14\x13" if black else b"\xE9\xE7\xE1") * scale
        for _ in range(scale):
            raw += b"\x00" + line

    def chunk(tag, body):
        c = struct.pack(">I", len(body)) + tag + body
        return c + struct.pack(">I", zlib.crc32(tag + body) & 0xFFFFFFFF)

    png = b"\x89PNG\r\n\x1a\n"
    png += chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 2, 0, 0, 0))
    png += chunk(b"IDAT", zlib.compress(bytes(raw), 9))
    png += chunk(b"IEND", b"")
    with open(path, "wb") as f:
        f.write(png)


def preview(glyph_map, ascent, descent, sample, path, scale):
    """Draws the sample the way gfx_text_font() will: pen on the baseline."""
    line_h = ascent + descent
    width = sum(glyph_map[c][4] if c in glyph_map else glyph_map["?"][4] for c in sample)
    canvas = [[False] * (width + 4) for _ in range(line_h + 4)]
    pen = 2
    base = 2 + ascent
    for c in sample:
        g = glyph_map.get(c) or glyph_map["?"]
        w, h, left, top, adv, rows = g
        for y in range(h):
            for x in range(w):
                if rows[y][x]:
                    px, py = pen + left + x, base - top + y
                    if 0 <= py < len(canvas) and 0 <= px < len(canvas[0]):
                        canvas[py][px] = True
        pen += adv
    write_png(path, canvas, scale)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("font")
    ap.add_argument("--px", type=int, required=True, help="pixel size (em)")
    ap.add_argument("--name", required=True, help="C identifier of the font")
    ap.add_argument("--out", required=True)
    ap.add_argument("--chars", default="", help="extra characters to include")
    ap.add_argument("--only", help="include only these characters (plus '?')")
    ap.add_argument("--var", default="", help="variable font axes, e.g. wght=400,wdth=100")
    ap.add_argument("--preview", help="PNG of --sample")
    ap.add_argument("--sample", default="perINKpheraL ver 1.234.5 (c) 2026 Max Grakov MIT License")
    ap.add_argument("--preview-scale", type=int, default=3)
    a = ap.parse_args()

    face = freetype.Face(a.font)
    if a.var:
        want = dict(kv.split("=") for kv in a.var.split(","))
        axes = face.get_variation_info().axes
        face.set_var_design_coords([float(want.get(ax.tag, ax.default)) for ax in axes])
    face.set_pixel_sizes(0, a.px)
    ascent = (face.size.ascender + 32) >> 6
    descent = -((face.size.descender - 32) >> 6)

    chars = list(dict.fromkeys(ASCII + list(a.chars)))
    if a.only:
        chars = list(dict.fromkeys(list(a.only) + ["?"]))
    glyphs = []
    glyph_map = {}
    bits = bytearray()
    missing = []
    for ch in chars:
        g = render(face, ord(ch))
        if g is None:
            missing.append(ch)
            continue
        w, h, left, top, adv, rows = g
        glyph_map[ch] = g
        glyphs.append((ord(ch), w, h, left, top, adv, len(bits)))
        bits += pack_rows(rows, w)
    glyphs.sort()
    if "?" not in glyph_map:
        sys.exit("the font has no '?', which is the fallback glyph")

    write_header(a.out, a.name, a.px, ascent, descent, glyphs, bits, os.path.relpath(a.font))
    if a.preview:
        preview(glyph_map, ascent, descent, a.sample, a.preview, a.preview_scale)
    print("%s: %d px, ascent %d, descent %d, %d glyphs, %d bytes of bitmaps%s"
          % (a.name, a.px, ascent, descent, len(glyphs), len(bits),
             ", missing: " + "".join(missing) if missing else ""))


if __name__ == "__main__":
    main()
