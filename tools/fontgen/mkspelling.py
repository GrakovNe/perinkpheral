"""Writes the tables by which the device spells in Latin letters what it has no glyphs for.

    tools/fontgen/mkspelling.py --out firmware/components/gfx/spelling.h

A script a table: Latin letters with marks lose the marks, Cyrillic and Greek
are spelled the way their languages are usually written in Latin. What is in
no table is drawn as "?". The glyphs themselves come in packs (mkpack.py);
these tables are what shows while a pack is not there.
"""
import argparse
import unicodedata

CYRILLIC = {
    "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ж": "zh", "з": "z", "и": "i",
    "й": "y", "к": "k", "л": "l", "м": "m", "н": "n", "о": "o", "п": "p", "р": "r", "с": "s",
    "т": "t", "у": "u", "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
    "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya", "ё": "e",
    # Ukrainian, Belarusian
    "є": "ye", "і": "i", "ї": "yi", "ґ": "g", "ў": "u",
    # Serbian, Macedonian
    "ђ": "dj", "ј": "j", "љ": "lj", "њ": "nj", "ћ": "c", "џ": "dz", "ѓ": "g", "ќ": "k",
    "ѕ": "dz", "ѐ": "e", "ѝ": "i",
    # Kazakh
    "ә": "a", "ғ": "g", "қ": "q", "ң": "n", "ө": "o", "ұ": "u", "ү": "u", "һ": "h",
}
GREEK = {
    "α": "a", "β": "v", "γ": "g", "δ": "d", "ε": "e", "ζ": "z", "η": "i", "θ": "th", "ι": "i",
    "κ": "k", "λ": "l", "μ": "m", "ν": "n", "ξ": "x", "ο": "o", "π": "p", "ρ": "r", "σ": "s",
    "ς": "s", "τ": "t", "υ": "y", "φ": "f", "χ": "ch", "ψ": "ps", "ω": "o",
}
LATIN = {
    "ß": "ss", "æ": "ae", "œ": "oe", "ø": "o", "đ": "d", "ð": "d", "þ": "th", "ł": "l", "ħ": "h",
    "ı": "i", "ĸ": "k", "ŋ": "n", "ŧ": "t", "ſ": "s", "ĳ": "ij", "ŀ": "l", "ŉ": "n",
}
SIGNS = {
    0xA0: " ", 0x2013: "-", 0x2014: "-", 0x2018: "'", 0x2019: "'", 0xAB: '"', 0xBB: '"',
    0x201C: '"', 0x201D: '"', 0x201E: '"', 0x2026: "...", 0x2116: "No", 0x20AC: "EUR",
    0xD7: "x", 0xB7: ".", 0x2022: "*", 0x2212: "-",
}


def capital(spelled):
    return spelled[:1].upper() + spelled[1:]


def spelling(cp):
    """How the character is written in ASCII, or None."""
    if cp in SIGNS:
        return SIGNS[cp]
    char = chr(cp)
    small = char.lower()
    for table in (CYRILLIC, GREEK, LATIN):
        if small in table:
            return table[small] if char == small else capital(table[small])
    # A letter with a mark is its letter: what is left of it taken apart.
    parts = unicodedata.normalize("NFD", char)
    base = "".join(c for c in parts if not unicodedata.combining(c))
    if base != char and base and all(0x20 < ord(c) < 0x7F for c in base):
        return base
    if len(base) == 1 and base != char:
        return spelling(ord(base))
    return None


RANGES = [("LATIN", 0x00A0, 0x017F), ("GREEK", 0x0386, 0x03CE), ("CYRILLIC", 0x0400, 0x04FF),
          ("SIGNS", 0x2010, 0x2030)]


def main():
    args = argparse.ArgumentParser(description=__doc__,
                                   formatter_class=argparse.RawDescriptionHelpFormatter)
    args.add_argument("--out", required=True)
    options = args.parse_args()
    lines = ["/* generated by tools/fontgen/mkspelling.py - do not edit */", "#pragma once", "",
             "#include <stdint.h>", "",
             "/* How a character the device has no glyph for is spelled in ASCII: a table a",
             " * range of code points, NULL for what has no spelling. */", ""]
    for name, first, last in RANGES:
        lines.append("static const char *const SPELLING_%s[] = {" % name)
        for cp in range(first, last + 1):
            spelled = spelling(cp) if cp not in (0x20AC, 0x2116) or name == "SIGNS" else None
            text = "NULL" if spelled is None else '"%s"' % spelled.replace("\\", "\\\\").replace('"', '\\"')
            lines.append("    /* U+%04X */ %s," % (cp, text))
        lines.append("};")
        lines.append("")
    lines.append("static const struct {")
    lines.append("    uint16_t           first, last;")
    lines.append("    const char *const *spelled;")
    lines.append("} SPELLINGS[] = {")
    for name, first, last in RANGES:
        lines.append("    { 0x%04X, 0x%04X, SPELLING_%s }," % (first, last, name))
    lines.append("};")
    lines.append("")
    extra = sorted(cp for cp in SIGNS if not any(first <= cp <= last for _, first, last in RANGES))
    lines.append("static const struct {")
    lines.append("    uint16_t    cp;")
    lines.append("    const char *spelled;")
    lines.append("} SPELLING_SINGLES[] = {")
    for cp in extra:
        lines.append('    { 0x%04X, "%s" },' % (cp, SIGNS[cp]))
    lines.append("};")
    with open(options.out, "w") as f:
        f.write("\n".join(lines) + "\n")
    count = sum(1 for _, first, last in RANGES for cp in range(first, last + 1) if spelling(cp) is not None)
    print("%s: %d characters spelled" % (options.out, count + len(extra)))


if __name__ == "__main__":
    main()
