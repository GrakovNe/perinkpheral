"""Turn a video into a 1-bit stream small enough to live inside an application.

    mkvideo.py <video> --out frames.h [--width 50] [--height 37] [--fps 2]
               [--threshold 128] [--name video]

The video is scaled to a few dozen pixels a side and cut to black and
white. A frame is stored as what changed since the frame before it: the
pixels in reading order, as runs - so many stay, so many flip, so many
stay - each run a number in the variable-length form below. A still
picture costs a few bytes a frame, and the decoder is a loop that fits in
a wasm application.

    a run of N:  N < 128        one byte, N
                 otherwise      the low seven bits with the top bit set,
                                then the rest the same way

Every frame's runs add up to width x height exactly. Needs ffmpeg.
"""
import argparse
import subprocess
import sys


def read_frames(video, width, height, fps, threshold):
    """Every frame as a list of bools, True where the picture is dark."""
    raw = subprocess.run(
        ["ffmpeg", "-v", "error", "-i", video, "-vf",
         "fps=%s,scale=%d:%d:flags=area" % (fps, width, height),
         "-pix_fmt", "gray", "-f", "rawvideo", "-"],
        capture_output=True, check=True).stdout
    size = width * height
    return [[level < threshold for level in raw[at:at + size]]
            for at in range(0, len(raw) - size + 1, size)]


def variable_length(number):
    encoded = bytearray()
    while number >= 0x80:
        encoded.append(number & 0x7F | 0x80)
        number >>= 7
    encoded.append(number)
    return encoded


def encode(frames):
    encoded = bytearray()
    shown = [False] * len(frames[0])  # the picture starts white
    for frame in frames:
        run_flips, run_length = False, 0  # a frame starts with pixels that stay
        for was, now in zip(shown, frame):
            flips = was != now
            if flips != run_flips:
                encoded += variable_length(run_length)
                run_flips, run_length = flips, 0
            run_length += 1
        encoded += variable_length(run_length)
        shown = frame
    return encoded


def write_header(path, name, width, height, fps, frame_count, encoded, source):
    with open(path, "w") as header:
        header.write("/* generated by tools/mkvideo/mkvideo.py from %s - do not edit */\n" % source)
        header.write("#pragma once\n\n#include <stdint.h>\n\n")
        header.write("#define %s_WIDTH  %d\n#define %s_HEIGHT %d\n" % (name.upper(), width, name.upper(), height))
        header.write("#define %s_FRAMES %d\n" % (name.upper(), frame_count))
        header.write("#define %s_FRAMES_PER_10_S %d\n\n" % (name.upper(), round(fps * 10)))
        header.write("static const uint8_t %s_runs[%d] = {\n" % (name, len(encoded)))
        for at in range(0, len(encoded), 20):
            header.write("    " + ",".join("%d" % byte for byte in encoded[at:at + 20]) + ",\n")
        header.write("};\n")


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("video")
    parser.add_argument("--out", required=True)
    parser.add_argument("--width", type=int, default=50)
    parser.add_argument("--height", type=int, default=37)
    parser.add_argument("--fps", type=float, default=2)
    parser.add_argument("--threshold", type=int, default=128,
                        help="a pixel darker than this (0-255) is ink")
    parser.add_argument("--name", default="video", help="the C name of the data")
    options = parser.parse_args()

    frames = read_frames(options.video, options.width, options.height, options.fps,
                         options.threshold)
    if not frames:
        sys.exit("no frames came out of %s" % options.video)
    encoded = encode(frames)
    write_header(options.out, options.name, options.width, options.height, options.fps,
                 len(frames), encoded, options.video.rsplit("/", 1)[-1])
    print("%s: %d frames of %dx%d, %d bytes, %.1f bytes a frame"
          % (options.out, len(frames), options.width, options.height, len(encoded),
             len(encoded) / len(frames)))


if __name__ == "__main__":
    main()
